// Generates src/abi.generated.ts from the program headers, so the SDK can never drift from the program.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const here = dirname(fileURLToPath(import.meta.url));
const prog = join(here, "..", "..", "program");
const src = ["flowstate_core.h", "flowstate_abi.h"].map((f) => readFileSync(join(prog, f), "utf8")).join("\n");
const out = [];
out.push("// GENERATED by scripts/gen-abi.mjs from thru/program/*.h. Do not edit.");
const nums = new Map();
for (const m of src.matchAll(/#define\s+(FS_[A-Z0-9_]+)\s+\(?(0x[0-9A-Fa-f]+|\d+)(?:ULL|u|U)?\b/g)) nums.set(m[1], m[2]);
for (const m of src.matchAll(/(FS_[A-Z0-9_]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)/g)) nums.set(m[1], m[2]);
out.push("export const C = {");
for (const [k, v] of [...nums].sort()) out.push(`  ${k}: ${v},`);
out.push("} as const;");
const tags = [...src.matchAll(/#define\s+(FS_SEED_TAG_[A-Z]+)\s+"([^"]+)"/g)];
out.push("export const SEED_TAGS = {");
for (const m of tags) out.push(`  ${m[1]}: ${JSON.stringify(m[2])},`);
out.push("} as const;");
const errs = [...nums].filter(([k]) => k.startsWith("FS_ERR_"));
out.push("export const ERROR_NAMES: Record<number, string> = {");
for (const [k, v] of errs) out.push(`  [${v}]: ${JSON.stringify(k.replace("FS_ERR_", ""))},`);
out.push("};");
writeFileSync(join(here, "..", "src", "abi.generated.ts"), out.join("\n") + "\n");
console.log(`abi.generated.ts: ${nums.size} constants, ${tags.length} seed tags, ${errs.length} errors`);
